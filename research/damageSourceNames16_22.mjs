// Builds src/core/damageSourceNames16_22.js from a local 16.22.8348910 install.
// Damage events name their spell with a lowercase ELF hash of its script name.
// Champion spells are read from the player's champion file at runtime. This
// collects the shared names: items, summoner spells, runes and map augments.
//
// node research/damageSourceNames16_22.mjs "C:\Riot Games\League of Legends"
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readWadScriptNames, RUNE_SCRIPT_FIELD, SCRIPT_NAME_FIELD } from '../src/core/damageSources.js';

const league = process.argv[2] || 'C:\\Riot Games\\League of Legends';
const final = path.join(league, 'Game', 'DATA', 'FINAL');
const files = [
  'Global.wad.client',
  ...['Common', 'Map11', 'Map12', 'Map22', 'Map30'].map((name) => path.join('Maps', 'Shipping', `${name}.wad.client`))
].map((file) => path.join(final, file)).filter((file) => fs.existsSync(file));

// Keep names that can own damage outside a champion's own kit.
const shared = /^(?:\d{4,6}[A-Za-z_]*|Augment_[A-Za-z0-9_]+|Summoner[A-Za-z0-9_]+|[A-Za-z]*Snowball[A-Za-z0-9_]*|Item[A-Za-z0-9_]+|Burning|ASSETS\/Perks\/Styles\/[A-Za-z]+\/[A-Za-z0-9_]+\/[A-Za-z0-9_]+\.lua)$/;
const names = new Set();
for (const file of files) {
  const found = await readWadScriptNames(file, { fields: [SCRIPT_NAME_FIELD, RUNE_SCRIPT_FIELD], maxEntries: 200000, maxEntrySize: 8 * 1024 * 1024, maxNames: 1000000 });
  let kept = 0;
  for (const name of found) if (shared.test(name) && !names.has(name)) { names.add(name); kept++; }
  console.error(`${path.basename(file)}: ${found.size} script names, ${kept} new shared names`);
}
const sorted = [...names].sort();
const output = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'core', 'damageSourceNames16_22.js');
fs.writeFileSync(output, `// Generated by research/damageSourceNames16_22.mjs from 16.22.8348910 game data.\n` +
  `// Shared spell script names. Damage events carry their lowercase ELF hashes.\n` +
  `export const SHARED_SOURCE_NAMES = ${JSON.stringify(sorted.join('\n'))}.split('\\n');\n`);
console.error(`Wrote ${sorted.length} names to ${output}`);
